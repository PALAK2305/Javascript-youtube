const month = "mar"

switch (month) {
    case "january":
        console.log("january");
        break;
    case "feb":
        console.log("feb");
        break;
    case "mar":
        console.log("mar");
        break;
    case "april":
        console.log("april");
        break;

    default:
        console.log("default");
        break;
}